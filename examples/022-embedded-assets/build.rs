//! Build script: version metadata and generated code.
//!
//! - `cargo:rustc-env=...` – values for `env!()` (git commit, build date),
//! - a generated Rust file in `OUT_DIR`, pulled in with `include!` – code computed at build time.
//!
//! Crates like `vergen` / `built` / `shadow-rs` do the metadata part with less code.

use std::{env, fs, path::Path, process::Command};

fn main() {
    let commit = Command::new("git")
        .args(["rev-parse", "--short", "HEAD"])
        .output()
        .ok()
        .filter(|output| output.status.success())
        .map(|output| String::from_utf8_lossy(&output.stdout).trim().to_string())
        // Building from a crates.io package or a tarball: no git repository.
        .unwrap_or_else(|| "unknown".into());
    println!("cargo:rustc-env=GIT_COMMIT={commit}");

    // Respect SOURCE_DATE_EPOCH for reproducible builds (same input -> same binary).
    let date = env::var("SOURCE_DATE_EPOCH").unwrap_or_else(|_| {
        std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .map(|d| d.as_secs().to_string())
            .unwrap_or_default()
    });
    println!("cargo:rustc-env=BUILD_EPOCH={date}");

    // Generated code: the list of template files, known at compile time.
    let mut names: Vec<String> = Vec::new();
    collect(Path::new("templates"), Path::new("templates"), &mut names);
    names.sort();
    let generated = format!(
        "/// Generated by build.rs from the `templates/` directory.\npub const TEMPLATE_FILES: &[&str] = &{names:?};\n"
    );
    let out_dir = env::var("OUT_DIR").expect("cargo sets OUT_DIR");
    fs::write(Path::new(&out_dir).join("generated.rs"), generated).expect("write generated.rs");

    // Re-run when templates or git HEAD change (otherwise cargo caches the build script output).
    println!("cargo:rerun-if-changed=templates");
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=../../.git/HEAD");
}

fn collect(root: &Path, dir: &Path, names: &mut Vec<String>) {
    let Ok(entries) = fs::read_dir(dir) else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            collect(root, &path, names);
        } else if let Ok(relative) = path.strip_prefix(root) {
            names.push(relative.to_string_lossy().replace('\\', "/"));
        }
    }
}
