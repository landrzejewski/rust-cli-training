//! `platctl-new` – step 022: shipping assets inside the executable.
//!
//! ```text
//! platctl-new list                          embedded templates
//! platctl-new create <NAME> [--team T] [--dir D]   scaffold a service from templates
//! platctl-new default-config                print the embedded default config
//! platctl-new logo <FILE>                   write the embedded PNG
//! platctl-new --version                     version + git commit + build date (build.rs)
//! ```
//!
//! A single file to distribute: no "where are my templates installed?" problems, works from any
//! directory, in containers, after `cargo install`.

use std::{
    fs,
    path::{Path, PathBuf},
};

use anyhow::Context;
use clap::{Parser, Subcommand};
use rust_embed::RustEmbed;

/// `include_str!` – a UTF-8 file becomes a `&'static str` in the binary at compile time.
/// The path is relative to THIS source file. Changing the file triggers a rebuild.
const DEFAULT_CONFIG: &str = include_str!("../assets/default-config.toml");

/// `include_bytes!` – any file as `&'static [u8; N]` (images, certificates, WASM, fonts).
const LOGO_PNG: &[u8] = include_bytes!("../assets/logo.png");

/// `rust-embed` – a whole DIRECTORY. The derive generates `Templates::get(path)` and
/// `Templates::iter()`. In release builds files are embedded; in debug builds they are read
/// from disk at runtime by default (edit templates without recompiling; feature `debug-embed`
/// embeds in debug too).
#[derive(RustEmbed)]
#[folder = "templates/"]
struct Templates;

// Code generated by build.rs (`TEMPLATE_FILES`), included verbatim at this place.
include!(concat!(env!("OUT_DIR"), "/generated.rs"));

/// Long version: `--version` shows build metadata from build.rs.
const LONG_VERSION: &str = concat!(
    env!("CARGO_PKG_VERSION"),
    " (commit ",
    env!("GIT_COMMIT"),
    ", built ",
    env!("BUILD_EPOCH"),
    ")"
);

/// Scaffold new platform services from embedded templates.
#[derive(Debug, Parser)]
#[command(name = "platctl-new", version = LONG_VERSION)]
struct Cli {
    #[command(subcommand)]
    command: Command,
}

#[derive(Debug, Subcommand)]
enum Command {
    /// List embedded template files
    List,
    /// Create a new service from the `service` template
    Create {
        /// Service name (also the crate name)
        name: String,
        /// Owning team
        #[arg(long, default_value = "platform")]
        team: String,
        /// Target directory [default: ./<NAME>]
        #[arg(long)]
        dir: Option<PathBuf>,
    },
    /// Print the embedded default configuration
    DefaultConfig,
    /// Write the embedded logo to a file
    Logo { file: PathBuf },
}

fn main() -> anyhow::Result<()> {
    match Cli::parse().command {
        Command::List => {
            for path in Templates::iter() {
                let size = Templates::get(&path).map_or(0, |file| file.data.len());
                println!("{path:<30} {size:>5} B");
            }
            eprintln!(
                "({} files, known at build time: {:?})",
                TEMPLATE_FILES.len(),
                TEMPLATE_FILES
            );
        }
        Command::Create { name, team, dir } => {
            let dir = dir.unwrap_or_else(|| PathBuf::from(&name));
            let written = scaffold(&dir, &name, &team)?;
            for path in written {
                println!("created {}", path.display());
            }
        }
        Command::DefaultConfig => print!("{DEFAULT_CONFIG}"),
        Command::Logo { file } => {
            fs::write(&file, LOGO_PNG)
                .with_context(|| format!("cannot write {}", file.display()))?;
            println!("wrote {} ({} bytes)", file.display(), LOGO_PNG.len());
        }
    }
    Ok(())
}

/// Renders every `service/...tmpl` file into `dir`, replacing `{{name}}` and `{{team}}`.
fn scaffold(dir: &Path, name: &str, team: &str) -> anyhow::Result<Vec<PathBuf>> {
    anyhow::ensure!(
        !dir.exists(),
        "{} already exists – refusing to overwrite",
        dir.display()
    );
    let mut written = Vec::new();
    for path in Templates::iter().filter(|p| p.starts_with("service/")) {
        let file = Templates::get(&path).context("embedded file disappeared")?;
        let text = std::str::from_utf8(&file.data).context("template is not UTF-8")?;
        let rendered = render(text, name, team);

        let relative = path
            .trim_start_matches("service/")
            .trim_end_matches(".tmpl");
        let target = dir.join(relative);
        if let Some(parent) = target.parent() {
            fs::create_dir_all(parent)?;
        }
        fs::write(&target, rendered)
            .with_context(|| format!("cannot write {}", target.display()))?;
        written.push(target);
    }
    written.sort();
    Ok(written)
}

/// Minimal placeholder substitution. Real tools use a template engine (minijinja, tera, handlebars).
fn render(template: &str, name: &str, team: &str) -> String {
    template.replace("{{name}}", name).replace("{{team}}", team)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn embedded_files_are_available() {
        assert!(DEFAULT_CONFIG.contains("[api]"));
        assert_eq!(&LOGO_PNG[..4], b"\x89PNG");
        assert!(Templates::get("service/Cargo.toml.tmpl").is_some());
        assert_eq!(TEMPLATE_FILES.len(), Templates::iter().count());
    }

    #[test]
    fn scaffold_renders_placeholders_and_refuses_to_overwrite() {
        let dir = std::env::temp_dir().join(format!("platctl-new-test-{}", std::process::id()));

        let written = scaffold(&dir, "payments-api", "payments").unwrap();
        let cargo = fs::read_to_string(dir.join("Cargo.toml")).unwrap();
        let main = fs::read_to_string(dir.join("src/main.rs")).unwrap();

        assert_eq!(written.len(), 4);
        assert!(cargo.contains("name = \"payments-api\""));
        assert!(main.contains("owned by team payments"));
        assert!(scaffold(&dir, "x", "y").is_err());
        fs::remove_dir_all(dir).unwrap();
    }

    #[test]
    fn version_contains_commit() {
        assert!(LONG_VERSION.contains("commit "));
    }
}
